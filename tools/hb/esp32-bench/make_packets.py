#!/usr/bin/env python3
"""Builds include/packets.h for the benchmark: a set of FABRICATED packets whose length distribution follows the lengths of real LoRa APRS traffic
(quantiles of 14,305 real packets; only these numbers are used, no real text), plus the two hand-made stress cases in stress_packets.txt.
  python3 make_packets.py ../gen_packets_output.txt [N] > include/packets.h      (run from tools/hb/esp32-bench; the input is gen_packets.py 30000)"""
import random, sys
Q = [(0, 23), (5, 38), (10, 39), (25, 54), (50, 80), (75, 110), (90, 126), (95, 151), (99, 183)]     # percentile, packet length (characters)
pool = [l.rstrip(b'\n') for l in open(sys.argv[1], 'rb') if l.strip()]
N = int(sys.argv[2]) if len(sys.argv) > 2 else 400
random.seed(110031)
by = {}
for p in pool: by.setdefault(len(p), []).append(p)
def inv(u):                                                   # inverse CDF, linear between the quantiles
    for (p0, l0), (p1, l1) in zip(Q, Q[1:]):
        if u <= p1: return l0 + (l1 - l0) * (u - p0) / max(p1 - p0, 1e-9)
    return Q[-1][1]
chosen = []
while len(chosen) < N:
    t = round(inv(random.random() * 99))
    for d in sorted(range(-6, 7), key=abs):
        c = by.get(t + d)
        if c: chosen.append(c.pop(random.randrange(len(c)))); break
    else: continue
stress = [l.rstrip(b'\n') for l in open('stress_packets.txt', 'rb') if l.strip()]
def esc(b): return '"' + ''.join('\\%03o' % c if c < 32 or c > 126 or chr(c) in '"\\?' else chr(c) for c in b) + '"'
print('// fabricated packets whose lengths follow real traffic (quantiles only) and %d stress cases; generated by make_packets.py' % len(stress))
print('static const char *const PACKETS[] = {')
for p in chosen: print('  %s,' % esc(p))
print('};\n#define PACKETS_N %d' % len(chosen))
print('static const char *const STRESS[] = {')
for p in stress: print('  %s,' % esc(p))
print('};\n#define STRESS_N %d' % len(stress))
